-- tests/migration_spec.lua (old key names are intentional)
local OLD_POS, NEW_POS, OLD_PIN, NEW_PIN = "BufferlinePositions", "BufferlinesPositions", "BufferlinePinnedBuffers", "BufferlinesPinnedBuffers"
describe("persisted globals read-through", function()
  local a, b, c
  local function path(buf) return vim.api.nvim_buf_get_name(buf) end
  local function enc(...) return vim.json.encode(vim.tbl_map(path, { ... })) end
  local function boot()
    for k in pairs(package.loaded) do if k:match("^bufferlines") then package.loaded[k] = nil end end
    require("bufferlines").setup({ options = { persist_buffer_sort = true } })
    vim.api.nvim_exec_autocmds("SessionLoadPost", {})
    return require("bufferlines.state"), require("bufferlines.groups")
  end
  before_each(function()
    vim.cmd("silent! %bwipeout!")
    for _, k in ipairs({ OLD_POS, NEW_POS, OLD_PIN, NEW_PIN }) do vim.g[k] = nil end
    local dir = vim.fn.tempname(); vim.fn.mkdir(dir, "p")
    vim.cmd.edit(dir .. "/a.txt"); a = vim.fn.bufnr("%"); vim.cmd.edit(dir .. "/b.txt"); b = vim.fn.bufnr("%")
    vim.cmd.edit(dir .. "/c.txt"); c = vim.fn.bufnr("%")
  end)
  it("imports old keys when the new ones are nil", function()
    vim.g[OLD_POS], vim.g[OLD_PIN] = enc(c, a, b), path(a)
    local state, groups = boot()
    assert.same({ c, a, b }, state.custom_sort); assert.is_true(groups._is_pinned({ id = a }))
    assert.equals(enc(c, a, b), vim.g[NEW_POS]); assert.equals(enc(c, a, b), vim.g[OLD_POS]); assert.equals(path(a), vim.g[OLD_PIN])
    require("bufferlines.utils").save_positions({ a, b, c })
    assert.equals(enc(a, b, c), vim.g[NEW_POS]); assert.equals(enc(c, a, b), vim.g[OLD_POS])
  end)
  it("prefers the new keys when both exist", function()
    vim.g[OLD_POS], vim.g[NEW_POS], vim.g[OLD_PIN], vim.g[NEW_PIN] = enc(c, a, b), enc(b, c, a), path(a), path(b)
    local state, groups = boot()
    assert.same({ b, c, a }, state.custom_sort); assert.is_true(groups._is_pinned({ id = b })); assert.is_false(groups._is_pinned({ id = a }))
  end)
  it("treats explicitly empty new keys as set", function()
    vim.g[OLD_POS], vim.g[NEW_POS], vim.g[OLD_PIN], vim.g[NEW_PIN] = enc(c, a, b), "", path(a), ""
    local state, groups = boot()
    assert.is_nil(state.custom_sort); assert.is_false(groups._is_pinned({ id = a })); assert.is_false(groups._is_pinned({ id = c }))
    assert.equals("", vim.g[NEW_PIN]); assert.equals(path(a), vim.g[OLD_PIN])
  end)
  it("does nothing when neither key exists", function()
    local state = boot()
    assert.is_nil(state.custom_sort); assert.is_nil(vim.g[NEW_POS]); assert.is_nil(vim.g[NEW_PIN]); assert.is_nil(vim.g[OLD_POS])
  end)
  it("never re-imports either key after the first copy", function()
    vim.g[OLD_POS], vim.g[OLD_PIN] = enc(c, a, b), path(a)
    local _, first = boot(); assert.is_true(first._is_pinned({ id = a }))
    vim.g[OLD_POS], vim.g[OLD_PIN] = enc(a, b, c), path(b)
    local state, groups = boot()
    assert.same({ c, a, b }, state.custom_sort)
    assert.is_false(groups._is_pinned({ id = b })); assert.is_true(groups._is_pinned({ id = a }))
    assert.equals(path(a), vim.g[NEW_PIN]); assert.equals(path(b), vim.g[OLD_PIN])
  end)
end)
